package com.zhikeban.bishe.rag;

/**
 * RAG 链路的**阶段标识**（`ENG-012` 任务①；详设 §4.3.2 的阶段枚举）。
 *
 * <p>★ 语义：{@code DegradeException.stage} 直接给出"降级发生在哪一步"，
 * 用于埋点（`rag.stage.duration`）与降级链的分支选择。
 *
 * <p>★ 六阶段（本单要求"逐个可核"）：受理提问 → 混合检索 → 权限过滤 → 提示词组装 → 流式生成 → 引用回填。
 */
public enum RagStage {

    /** ① 受理提问：校验请求（鉴权、限流、敏感词）。 */
    VALIDATE,

    /** ①② 之间：查询改写（指代消解）。 */
    REWRITE,

    /** ② 混合检索：向量一路 + 全文一路，并行召回与 RRF 融合。 */
    RETRIEVE,

    /** ③ 权限过滤：课程级 + 成员级过滤（**越权防线**，宁空不漏）。 */
    FILTER,

    /** ④ 提示词组装：系统提示 + 编号片段 + 最近对话 + 当前问题。 */
    PROMPT,

    /** ⑤ 流式生成：本地优先 → API 备选 → 全文检索兜底。 */
    GENERATE,

    /** ⑥ 引用回填：越界编号（模型编造）一律剔除。 */
    CITE
}
